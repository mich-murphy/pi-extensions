import { describe, expect, test } from "vitest";
import { inspectBashCommand } from "../output-safety";

describe("shell execution versus data", () => {
  test.each([
    "cat > /tmp/body <<'EOF'\nDo not use `cat` + `which`/`command -v`.\nEOF",
    'cat <<"EOF"\ncat $(which node)\nEOF',
    "cat <<E'OF'\ncat $(which node)\nEOF",
    "cat <<\\EOF\ncat $(which node)\nEOF",
    "cat <<-'EOF'\n\tcat $(which node)\n\tEOF",
    "printf '%s' 'cat $(which node)'",
    "cat '$(which node)'",
    'printf "%s" "cat" "$(which node)"',
    'printf hi > "$(which node)"',
    '"{" cat "$(which node)"',
    "'{' cat \"$(which node)\"",
    'printf "%s" "{" "$(which node)"',
    'env { cat "$(which node)"',
    'X=1 { cat "$(which node)"',
    'cat "$((which + 1))"',
    'cat "$((command + which))"',
    "cat <<$'EOF'\ncat $(which node)\nEOF",
    "echo cat $(which node)",
    "# cat $(which node)\necho safe",
    "cat <<EOF\ncat $(which node)\nEOF",
    "cat <<EOF\n'$(which node)'\nEOF",
    "cat <<EOF\n\\$(cat $(which node))\nEOF",
    "cat <<'EOF'\n$(cat $(which node))\nEOF\necho safe",
    "cat <<E\\\nOF\ncat $(which node)\nEOF",
    "cat <<EOF\nEO\\\nF\nprintf '%s' 'cat $(which node)'",
    "cat <<'EOF'\ncat $(which node)\nEO\\\nF\nEOF",
    "cat 'literal'\"$(echo '$(which node)')\"",
    "cat <<EOF\ncat \\`which node\\`\nEOF",
  ])("allows inert data: %s", (command) => {
    expect(inspectBashCommand(command)).toBeUndefined();
  });

  test.each([
    'cat "$(which "node")"',
    'X=1 cat "$(which node)"',
    '{ cat "$(which node)"; }',
    'if { cat "$(which node)"; }; then :; fi',
    'printf x; { cat "$(command -v node)"; }',
    "cat <<$'EOF'\nsafe\nEOF\ncat \"$(which node)\"",
    'cat <<$"EOF"\nsafe\nEOF\ncat "$(which node)"',
    'cat <<$"EOF"\ncat $(which node)\nEOF',
    "cat <<$'E\\x4fF'\nsafe\nEOF",
    "cat <<$(which node)\nsafe\n$(which node)",
    'cat <<$(which node)\nsafe\n$(which node)\ncat "$(which node)"',
    'cat "$((1 + $(cat "$(which node)")))"',
    'cat "$((1 + $(which node)))"',
    'cat < "$(which node)"',
    'cat 0< "$(command -v node)"',
    '2>/tmp/err cat "$(which node)"',
    '< "$(which node)" cat',
    'if cat "$(which node)"; then :; fi',
    '/bin/cat "$(which node)"',
    'command cat "$(command -v node)"',
    'echo $( (cat "$(which node)"))',
    "cat $( (echo ignored); which node)",
    "cat $(echo $(which a) $(cat $(which b)))",
    "cat $(command -v 'node')",
    'cat $(which "node")',
    '"cat" "$(command -v node)"',
    "c'at' $(which node)",
    "echo $(cat $(which node))",
    'echo "$(cat "$(command -v node)")"',
    "echo `cat $(which node)`",
    "cat <<EOF\n$(cat $(which node))\nEOF",
    "cat <<EOF\n'$(cat $(which node))'\nEOF",
    "cat <<EOF\n`cat $(command -v node)`\nEOF",
    "cat <<'EOF'\nsafe\nEOF\ncat $(which node)",
    "cat <<'A' <<B\n$(cat $(which node))\nA\n$(cat $(which node))\nB",
    "cat <<EOF\n$(echo $(cat $(which node)))\nEOF",
    "cat $(echo $(which node))",
    "cat $(printf '%s' \"$(which node)\")",
    "cat 'prefix'\"$(which node)\"",
    'cat\\\n "$(which node)"',
    "cat <<E\\\nOF\n$(cat $(which node))\nEOF",
    "cat <<EOF\nEO\\\nF\ncat $(which node)",
    "cat <<EOF\n\\\\$(cat $(which node))\nEOF",
  ])("blocks executable substitutions: %s", (command) => {
    expect(inspectBashCommand(command)).toContain('file "$(which COMMAND)"');
  });
});
